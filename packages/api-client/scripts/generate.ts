/**
 * API client generator (`pnpm api-client:generate`, `pnpm api-client:check`).
 *
 * 1. Exports the OpenAPI schema from the Python app without a database
 *    (`uv run python -m english_learn_api.export_openapi` in services/api).
 * 2. Writes it to `openapi.json` and its TypeScript types (openapi-typescript)
 *    to `src/generated/schema.ts`, both formatted with the repository's
 *    Prettier config so `prettier --check` accepts them.
 *
 * `--check` regenerates in memory and fails when either committed file differs:
 * the API changed without regenerating the client. Needs uv (and Python, which
 * uv installs from services/api/.python-version).
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_DIR = join(PACKAGE_DIR, "..", "..");
const API_DIR = join(REPO_DIR, "services", "api");
const SCHEMA_FILE = join(PACKAGE_DIR, "openapi.json");
const TYPES_FILE = join(PACKAGE_DIR, "src", "generated", "schema.ts");

const HEADER = `// Generated by scripts/generate.ts from openapi.json (openapi-typescript) — do not edit.
// Run \`pnpm api-client:generate\` after changing the API.`;

function exportSchema(): string {
  const result = spawnSync(
    "uv",
    ["run", "--frozen", "python", "-m", "english_learn_api.export_openapi"],
    { cwd: API_DIR, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
  );
  if (result.error) throw new Error(`api-client: could not run uv: ${result.error.message}`);
  if (result.status !== 0) throw new Error(`api-client: schema export exited ${result.status}`);
  return result.stdout;
}

async function prettier(source: string, parser: "json" | "typescript"): Promise<string> {
  const config = (await resolveConfig(SCHEMA_FILE)) ?? {};
  return format(source, { ...config, parser });
}

/** The two generated files, keyed by path. */
export async function render(schemaJson: string): Promise<Map<string, string>> {
  const schema = JSON.parse(schemaJson) as OpenAPI3;
  const types = astToString(await openapiTS(schema));
  return new Map([
    [SCHEMA_FILE, await prettier(schemaJson, "json")],
    [TYPES_FILE, await prettier(`${HEADER}\n\n${types}`, "typescript")],
  ]);
}

async function cli(args: readonly string[]): Promise<number> {
  const check = args.includes("--check");
  const files = await render(exportSchema());
  const stale: string[] = [];
  for (const [file, expected] of files) {
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (current === expected) continue;
    if (check) {
      stale.push(relative(REPO_DIR, file));
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, expected);
    }
  }
  if (stale.length > 0) {
    console.error(`api-client: stale ${stale.join(", ")}. Run \`pnpm api-client:generate\`.`);
    return 1;
  }
  console.error(`api-client: ${check ? "up to date" : "generated"}`);
  return 0;
}

const entry = process.argv[1];
if (entry && import.meta.url === pathToFileURL(entry).href) {
  process.exitCode = await cli(process.argv.slice(2));
}
