/**
 * Corpus module generator (`pnpm build:corpus`, `pnpm corpus:check`).
 *
 * Writes `src/generated/corpus.ts`: one static `import` per `data/**\/*.json`
 * (sorted, so the output is deterministic) passed to `createCorpus`. Bundlers
 * (Metro, Jest) inline the JSON, so the app gets the corpus offline without a
 * filesystem or Zod at runtime. Content is validated before generating; in CI
 * `--check` fails when the committed module no longer matches `data/`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";
import { formatErrors, listJsonFiles, main as validate } from "./validate";
import type { ValidationError } from "../src/validate";

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_DATA_DIR = join(PACKAGE_DIR, "data");
const DEFAULT_OUT_FILE = join(PACKAGE_DIR, "src", "generated", "corpus.ts");

const HEADER = `// Generated by scripts/build-corpus.ts — do not edit. Run \`pnpm build:corpus\` after changing data/.
// The data is validated by \`pnpm validate:content\` in CI, so this module carries no Zod.`;

const toPosix = (path: string) => path.split("\\").join("/");

/** Renders the corpus module for corpus-relative `files`, importing them from `dataImportPath`. */
export async function renderCorpusModule(
  files: readonly string[],
  dataImportPath: string,
): Promise<string> {
  const sorted = [...files].map(toPosix).sort();
  const imports = sorted.map((file, i) => `import file${i} from "${dataImportPath}/${file}";`);
  const names = sorted.map((_, i) => `file${i}`).join(", ");
  const source = [
    HEADER,
    `import type { ContentFile } from "../schema/content-file";`,
    `import { createCorpus, type Corpus } from "../corpus/corpus";`,
    ...imports,
    "",
    `const files = [${names}] as unknown as readonly ContentFile[];`,
    "",
    `export const corpus: Corpus = createCorpus(files);`,
    "",
  ].join("\n");
  // Format with the repository config so `prettier --check` accepts the committed file.
  const config = (await resolveConfig(fileURLToPath(import.meta.url))) ?? {};
  return format(source, { ...config, parser: "typescript" });
}

export type BuildCorpusOptions = {
  readonly dataDir?: string;
  readonly outFile?: string;
  /** `write` regenerates the module; `check` only compares it. */
  readonly mode: "write" | "check";
};

export type BuildCorpusResult =
  | { readonly status: "written" | "up-to-date" | "stale" }
  | { readonly status: "invalid"; readonly errors: readonly ValidationError[] };

export async function buildCorpus({
  dataDir = DEFAULT_DATA_DIR,
  outFile = DEFAULT_OUT_FILE,
  mode,
}: BuildCorpusOptions): Promise<BuildCorpusResult> {
  const errors = validate(dataDir);
  if (errors.length > 0) return { status: "invalid", errors };

  const dataImportPath = toPosix(relative(dirname(outFile), dataDir));
  const expected = await renderCorpusModule(listJsonFiles(dataDir), dataImportPath);
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;

  if (mode === "check") return { status: current === expected ? "up-to-date" : "stale" };
  if (current !== expected) {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, expected);
  }
  return { status: "written" };
}

async function cli(args: readonly string[]): Promise<number> {
  const mode = args.includes("--check") ? "check" : "write";
  const result = await buildCorpus({ mode });
  switch (result.status) {
    case "invalid":
      console.error(formatErrors(result.errors));
      console.error(`corpus: content is invalid (${result.errors.length} error(s))`);
      return 1;
    case "stale":
      console.error("corpus: src/generated/corpus.ts is stale. Run `pnpm build:corpus`.");
      return 1;
    default:
      console.error(`corpus: ${result.status}`);
      return 0;
  }
}

const entry = process.argv[1];
if (entry && import.meta.url === pathToFileURL(entry).href) {
  process.exitCode = await cli(process.argv.slice(2));
}
