#!/usr/bin/env node
// Writes the service worker (sw.js) into a web export, with the precache manifest of that
// export: every file with the first 16 hex digits of its SHA-256 as its revision. Runs after
// `expo export -p web` (see the `export:web` scripts).
// Usage: node scripts/build-service-worker.mjs [--dir dist-e2e]   (default: dist)
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { serviceWorker } from "./service-worker.mjs";

/** Exported files the worker must not cache: host config, build metadata, itself, maps. */
const EXCLUDED = new Set(["_headers", "_redirects", "metadata.json", "sw.js"]);

const sha256Prefix = (content) => createHash("sha256").update(content).digest("hex").slice(0, 16);

async function* files(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* files(path);
    else if (entry.isFile()) yield path;
  }
}

/** The precache manifest of the export in `dir`, sorted by URL. index.html is the shell `/`. */
export async function precacheEntries(dir) {
  const entries = [];
  for await (const path of files(dir)) {
    const name = relative(dir, path).split(sep).join("/");
    if (EXCLUDED.has(name) || name.endsWith(".map")) continue;
    // `URL` percent-encodes exactly like the browser does for the request's pathname.
    const url = name === "index.html" ? "/" : new URL(name, "https://x/").pathname;
    entries.push({ url, revision: sha256Prefix(await readFile(path)) });
  }
  return entries.sort((a, b) => (a.url < b.url ? -1 : a.url > b.url ? 1 : 0));
}

/** A short hash of the whole manifest: it changes, and so do sw.js's bytes, iff a file does. */
export function versionOf(entries) {
  return sha256Prefix(entries.map(({ url, revision }) => `${url} ${revision}`).join("\n")).slice(
    0,
    12,
  );
}

/** The classic-script source of sw.js. */
export function renderServiceWorker({ version, precache }) {
  return [
    "// English Learn service worker. Generated by scripts/build-service-worker.mjs from",
    "// scripts/service-worker.mjs: do not edit.",
    '"use strict";',
    `(${serviceWorker.toString()})(self, ${JSON.stringify({ version, precache })});`,
    "",
  ].join("\n");
}

/** Generates `dir`/sw.js. */
export async function buildServiceWorker(dir) {
  const precache = await precacheEntries(dir);
  const version = versionOf(precache);
  await writeFile(join(dir, "sw.js"), renderServiceWorker({ version, precache }));
  return { version, files: precache.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dirFlag = process.argv.indexOf("--dir");
  const dir = fileURLToPath(
    new URL(`../${dirFlag === -1 ? "dist" : process.argv[dirFlag + 1]}`, import.meta.url),
  );
  const { version, files: count } = await buildServiceWorker(dir);
  console.log(
    `Service worker ${version}: ${count} files precached (${relative(process.cwd(), dir)}/sw.js).`,
  );
}
